#!/usr/bin/env python3
"""Make the site's clean addresses. Run from anywhere:

    python3 tools/build-pages.py

1. Profile pages: people/<id>/index.html for every team card in index.html
   (data-person="<id>"), copied from person.html with that person's title and
   link-preview text.
2. Section addresses: about/, news/, team/, publications/, classes/, videos/,
   gallery/, apply/, plus publications/<year>/ for every year in the
   Publications list and gallery/<album>/ for every Gallery album. Each is a
   tiny page that forwards to that place on the homepage; main.js then shows
   the clean address again. people/ forwards to team/.

Re-run it after adding a team member, a new publication year, or a Gallery
album, or after editing person.html. New papers, news, bios, projects and
talks do NOT need it. Standard library only; no installs needed.
"""
import html
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = 'https://interactivecomputinglab.github.io/'   # the public lab site, used for link previews
MARK = 'tools/build-pages.py'
OLD_MARK = 'tools/build-profiles.py'


def read(name):
    with open(os.path.join(ROOT, name), encoding='utf-8') as f:
        return f.read()


def write(rel_dir, text):
    out_dir = os.path.join(ROOT, rel_dir)
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, 'index.html'), 'w', encoding='utf-8') as f:
        f.write(text)


def attr(s):
    return html.escape(s, quote=True)


index = read('index.html')
template = read('person.html')
made = set()

# ---------------------------------------------------------------- 1. profiles
cards = re.findall(
    r'<div class="team-item" data-person="([a-z0-9-]+)">.*?'
    r'<h4 class="team-item-name">(?:<a [^>]*>)?(.*?)(?:</a>)?</h4>\s*'
    r'<span class="team-item-role">(.*?)</span>',
    index, re.S)
if not cards:
    raise SystemExit('No team cards with data-person="..." found in index.html')

for pid, name, role in cards:
    name = html.unescape(re.sub(r'<[^>]+>', '', name)).strip()
    role = html.unescape(re.sub(r'<[^>]+>', '', role)).strip()
    plain = re.sub(r'^Dr\.?\s+', '', name)
    title = '%s | Interactive Computing Lab' % plain
    desc = '%s, %s, Interactive Computing Lab at Stevens Institute of Technology: papers, projects, talks, and videos.' % (name, role)
    url = SITE + 'people/%s/' % pid

    page = template
    page = page.replace('<html class="no-js" lang="en">',
                        '<html class="no-js" lang="en" data-person="%s">' % pid, 1)
    page = page.replace('<meta charset="utf-8">\n',
                        '<meta charset="utf-8">\n'
                        '\t<!-- Generated by %s from person.html. Edit person.html instead, then re-run it. -->\n'
                        '\t<base href="../../">\n' % MARK, 1)
    page = re.sub(r'<title>.*?</title>', '<title>%s</title>' % html.escape(title), page, count=1)
    page = re.sub(r'<meta name="description" content="[^"]*">', '<meta name="description" content="%s">' % attr(desc), page, count=1)
    page = re.sub(r'<meta property="og:title" content="[^"]*">', '<meta property="og:title" content="%s">' % attr(title), page, count=1)
    page = re.sub(r'<meta property="og:description" content="[^"]*">', '<meta property="og:description" content="%s">' % attr(desc), page, count=1)
    page = re.sub(r'<meta property="og:image" content="[^"]*">',
                  '<meta property="og:image" content="%simg/team/%s.jpg">\n'
                  '\t<meta property="og:url" content="%s">\n'
                  '\t<link rel="canonical" href="%s">' % (SITE, pid, url, url), page, count=1)
    page = page.replace('<meta name="twitter:card" content="summary_large_image">', '<meta name="twitter:card" content="summary">', 1)
    write(os.path.join('people', pid), page)
    made.add('people/%s' % pid)

# ---------------------------------------------------------------- 2. forwarding addresses
FORWARD = '''<!doctype html>
<html lang="en">
<head>
	<meta charset="utf-8">
	<!-- Generated by {mark}: forwards to {label} on the homepage. Do not edit; re-run the script. -->
	<title>{title}</title>
	<meta name="description" content="{desc}">
	<meta name="viewport" content="width=device-width, initial-scale=1">
	<link rel="canonical" href="{url}">
	<meta property="og:title" content="{title}">
	<meta property="og:description" content="{desc}">
	<meta property="og:image" content="{site}img/og-image.png">
	<meta property="og:url" content="{url}">
	<meta name="twitter:card" content="summary_large_image">
	<link rel="icon" href="{up}img/favicon.png" sizes="64x64">
	<meta http-equiv="refresh" content="0; url={target}">
	<script>location.replace('{target}');</script>
	<style>body {{ font-family: sans-serif; background: #fff; color: #555; text-align: center; padding-top: 30vh; }} a {{ color: #B30C38; }}</style>
</head>
<body>
	<p><a href="{target}">{label} &middot; Interactive Computing Lab</a></p>
</body>
</html>
'''


def forward(path, anchor, label, desc):
    depth = path.count('/') + 1          # team -> ../ , gallery/dis2026 -> ../../
    up = '../' * depth
    target = up + '#' + anchor
    title = '%s | Interactive Computing Lab' % label
    text = FORWARD.format(mark=MARK, label=html.escape(label), title=html.escape(title), desc=attr(desc),
                          url=SITE + path + '/', site=SITE, up=up, target=target)
    write(path, text)
    made.add(path)


LAB = 'the Interactive Computing Lab at Stevens Institute of Technology'
sections = [
    ('about', 'about', 'About us', 'About ' + LAB + '.'),
    ('news', 'news', 'Recent News', 'Recent news from ' + LAB + '.'),
    ('team', 'team', 'Our Team', 'Faculty, students, and alumni of ' + LAB + '.'),
    ('people', 'team', 'Our Team', 'Faculty, students, and alumni of ' + LAB + '.'),
    ('publications', 'pubs', 'Publications', 'Papers published by ' + LAB + '.'),
    ('classes', 'classes', 'Classes', 'Classes taught by Dr. Jonggi Hong at Stevens Institute of Technology.'),
    ('videos', 'videos', 'Videos', 'Talks and videos from ' + LAB + '.'),
    ('gallery', 'gallery', 'Gallery', 'Photos from conferences, talks, and lab life at ' + LAB + '.'),
    ('apply', 'apply', 'Lab Openings', 'Join ' + LAB + ': openings for PhD, master’s, and undergraduate students.'),
]
for path, anchor, label, desc in sections:
    if anchor != 'pubs' and not re.search(r'<a name="%s"></a>' % anchor, index):
        print('warning: <a name="%s"> not found in index.html' % anchor)
    forward(path, anchor, label, desc)

for year in re.findall(r'<a name="pubs-(\d{4})"></a>', index):
    forward('publications/%s' % year, 'pubs-' + year, 'Publications %s' % year, 'Papers published in %s by %s.' % (year, LAB))

for album, title in re.findall(r'<div class="gallery-item" id="gallery-([a-z0-9-]+)".*?<h4 class="gallery-title">(.*?)</h4>', index, re.S):
    title = html.unescape(re.sub(r'<[^>]+>', '', title)).strip()
    forward('gallery/%s' % album, 'gallery-' + album, 'Gallery: %s' % title, 'Photos from %s, %s.' % (title, LAB))

# ---------------------------------------------------------------- report
stale = []
for dirpath, dirnames, filenames in os.walk(ROOT):
    rel = os.path.relpath(dirpath, ROOT).replace(os.sep, '/')
    if rel.startswith(('.git', 'img', 'css', 'js', 'fonts', 'tools')) or 'index.html' not in filenames or rel == '.':
        continue
    with open(os.path.join(dirpath, 'index.html'), encoding='utf-8') as f:
        head = f.read(600)
    if (MARK in head or OLD_MARK in head) and rel not in made:
        stale.append(rel + '/')

people = sorted(p for p in made if p.startswith('people/'))
print('Wrote %d profile pages and %d section addresses.' % (len(people), len(made) - len(people)))
print('  ' + '  '.join(sorted(p + '/' for p in made if not p.startswith('people/'))))
if stale:
    print('No longer used (delete these folders if they should go): ' + ', '.join(sorted(stale)))
