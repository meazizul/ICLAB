#!/usr/bin/env python3
"""Make one profile page per lab member: people/<id>/index.html.

Run from anywhere after adding a team member, or after changing person.html:

    python3 tools/build-profiles.py

It reads the team cards in index.html (data-person="<id>", name, role) and copies
person.html into people/<id>/index.html with that person's id, page title and
link-preview text. The page content itself is filled in by js/person.js, so you do
not need to re-run this when papers, news, bios, projects or talks change.
Standard library only; no installs needed.
"""
import html
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = 'https://interactivecomputinglab.github.io/'   # the public lab site, used for link previews
MARK = 'tools/build-profiles.py'


def read(name):
    with open(os.path.join(ROOT, name), encoding='utf-8') as f:
        return f.read()


def attr(s):
    return html.escape(s, quote=True)


index = read('index.html')
template = read('person.html')

cards = re.findall(
    r'<div class="team-item" data-person="([a-z0-9-]+)">.*?'
    r'<h4 class="team-item-name">(?:<a [^>]*>)?(.*?)(?:</a>)?</h4>\s*'
    r'<span class="team-item-role">(.*?)</span>',
    index, re.S)
if not cards:
    raise SystemExit('No team cards with data-person="..." found in index.html')

made = []
for pid, name, role in cards:
    name = html.unescape(re.sub(r'<[^>]+>', '', name)).strip()
    role = html.unescape(re.sub(r'<[^>]+>', '', role)).strip()
    plain = re.sub(r'^Dr\.?\s+', '', name)
    title = '%s | Interactive Computing Lab' % plain
    desc = '%s, %s, Interactive Computing Lab at Stevens Institute of Technology: papers, projects, talks, and videos.' % (name, role)
    url = SITE + 'people/%s/' % pid

    page = template
    page = page.replace('<html class="no-js" lang="en">',
                        '<html class="no-js" lang="en" data-person="%s">' % pid, 1)
    page = page.replace('<meta charset="utf-8">\n',
                        '<meta charset="utf-8">\n'
                        '\t<!-- Generated by %s from person.html. Edit person.html instead, then re-run it. -->\n'
                        '\t<base href="../../">\n' % MARK, 1)
    page = re.sub(r'<title>.*?</title>', '<title>%s</title>' % html.escape(title), page, count=1)
    page = re.sub(r'<meta name="description" content="[^"]*">', '<meta name="description" content="%s">' % attr(desc), page, count=1)
    page = re.sub(r'<meta property="og:title" content="[^"]*">', '<meta property="og:title" content="%s">' % attr(title), page, count=1)
    page = re.sub(r'<meta property="og:description" content="[^"]*">', '<meta property="og:description" content="%s">' % attr(desc), page, count=1)
    page = re.sub(r'<meta property="og:image" content="[^"]*">',
                  '<meta property="og:image" content="%simg/team/%s.jpg">\n'
                  '\t<meta property="og:url" content="%s">\n'
                  '\t<link rel="canonical" href="%s">' % (SITE, pid, url, url), page, count=1)
    page = page.replace('<meta name="twitter:card" content="summary_large_image">', '<meta name="twitter:card" content="summary">', 1)

    out_dir = os.path.join(ROOT, 'people', pid)
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, 'index.html'), 'w', encoding='utf-8') as f:
        f.write(page)
    made.append(pid)

# Folders for people who are no longer on the team page (only ones this script made)
stale = []
people_dir = os.path.join(ROOT, 'people')
for d in sorted(os.listdir(people_dir)):
    f = os.path.join(people_dir, d, 'index.html')
    if d not in made and os.path.isfile(f) and MARK in open(f, encoding='utf-8').read():
        stale.append(d)

print('Wrote %d profile pages: people/<id>/index.html' % len(made))
for pid in made:
    print('  people/%s/' % pid)
if stale:
    print('Not on the team page any more (delete these folders if they should go): ' + ', '.join('people/%s/' % d for d in stale))
